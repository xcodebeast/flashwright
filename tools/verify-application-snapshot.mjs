import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { applicationEvidenceFiles, applicationEvidenceHashes, normalizeApplicationEvidence } from './application-snapshot.mjs';
import { verifyApplicationSuite } from './verify-application-suite.mjs';

assert.equal(process.argv.length, 3, 'Usage: verify-application-snapshot.mjs SNAPSHOT_DIRECTORY');
const directory = resolve(process.argv[2]);
const files = await applicationEvidenceFiles(directory);
const manifest = JSON.parse(files['snapshot.json']);
delete files['snapshot.json'];
assert.equal(manifest.schemaVersion, 1);
assert.equal(manifest.kind, 'portable-application-evidence');
assert.equal(manifest.numericObservationsUnchanged, true);
assert.deepEqual(applicationEvidenceHashes(files), manifest.exportedFileSha256, 'Snapshot bytes or inventory changed');
assert.deepEqual(Object.keys(manifest.originalFileSha256).sort(), Object.keys(files).sort());
for (const digest of Object.values(manifest.originalFileSha256)) assert.match(digest, /^[a-f0-9]{64}$/);
assert.deepEqual(normalizeApplicationEvidence(files, JSON.parse(files['inputs.json'])), files, 'Snapshot contains unnormalized execution paths');
const result = await verifyApplicationSuite(directory, { portable: true });
assert.equal(result.applicationName, manifest.applicationName);
console.log(JSON.stringify(result, null, 2));
