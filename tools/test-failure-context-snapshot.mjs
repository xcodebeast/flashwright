import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';

const sources = await Promise.all(['failure-context-snapshot.js', 'locator-runtime.js'].map(name => readFile(`packages/resident-runtime/${name}`, 'utf8')));
let clock = 100;
const originalDocument = {};
const body = { isConnected: true, ownerDocument: originalDocument };
originalDocument.body = body;
const environment = { document: originalDocument, Date: { now: () => clock }, createConditionRegistry: () => ({}) };
const createRuntime = vm.runInNewContext(sources.join('\n') + '\ncreateLocatorRuntime', environment);
let calls = 0;
let render = () => ({ full: '- button "Submit" [ref=e1]', iframeRefs: [], iframeDepths: {} });
const runtime = createRuntime({ incrementalAriaSnapshot(element, options) {
  calls++;
  assert.equal(element, body);
  assert.equal(options.mode, 'ai');
  assert.equal(options.refPrefix, '');
  return render();
} }, { encode: value => value });
const snapshot = () => runtime.failureContextSnapshot(200);

assert.equal((await snapshot()).value, '- button "Submit" [ref=e1]');
clock = 200;
assert.equal((await snapshot()).status, 'expired');
assert.equal(calls, 1, 'expired dispatch does no renderer work');
clock = 100;
render = () => { clock = 201; return { full: 'late', iframeRefs: [], iframeDepths: {} }; };
assert.equal((await snapshot()).status, 'expired');
clock = 100;
originalDocument.body = null;
assert.equal((await snapshot()).status, 'retry');
originalDocument.body = body;
render = () => { body.isConnected = false; return { full: 'detached', iframeRefs: [], iframeDepths: {} }; };
assert.equal((await snapshot()).status, 'retry');
body.isConnected = true;
render = () => { environment.document = {}; return { full: 'old document', iframeRefs: [], iframeDepths: {} }; };
assert.equal((await snapshot()).status, 'retry');
environment.document = originalDocument;
render = () => ({ full: '- iframe [ref=e2]', iframeRefs: ['e2'], iframeDepths: { e2: 0 } });
assert.equal((await snapshot()).status, 'unsupportedFrames', 'never publish a partial rendered frame tree as complete');
render = () => ({ full: '- button', iframeRefs: ['not-rendered'], iframeDepths: {} });
assert.equal((await snapshot()).value, '- button');
render = () => ({ full: '😀'.repeat(20000), iframeRefs: [], iframeDepths: {} });
const bounded = await snapshot();
assert.equal(bounded.status, 'success');
assert.ok(bounded.value.length <= 16384);
assert.match(bounded.value, /\n\[Page snapshot truncated: diagnostic size limit reached\.\]$/);
assert.equal(bounded.value.slice(0, bounded.value.indexOf('\n')).isWellFormed(), true);
render = () => { throw new Error('renderer failure'); };
assert.equal((await snapshot()).status, 'error', 'actual asynchronous safely wrapper carries the failure');
console.log('Private failure snapshot: deadline, original document, frame admission, exact ordinary text and bounded output passed.');
